// Real files, HTTP/SSE and durable SQLite; only model output is deterministic.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const net = require('node:net')
const { spawn, execFileSync } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '../..')
const pause = ms => new Promise(r => setTimeout(r, ms))
async function until(fn, name) { const end = Date.now()+20000; while (!await fn()) { assert.ok(Date.now()<end, name); await pause(80) } }
async function main() {
  const data = await fs.mkdtemp(path.join(root,'verification/runtime/file-changes-'))
  const folder = path.join(data,'project'); await fs.mkdir(folder)
  await fs.writeFile(path.join(folder,'main.py'),'print("before")\n')
  let child, base, log = ''
  async function start() {
    const portServer = net.createServer(); await new Promise(r=>portServer.listen(0,'127.0.0.1',r))
    const port = portServer.address().port; await new Promise(r=>portServer.close(r))
    child = spawn(path.join(root,'backend/.venv/Scripts/python.exe'), [path.join(root,'backend/tests/file_change_server.py'),String(port)], { cwd:path.join(root,'backend'), env:{...process.env,DATA_DIR:data,LLM_API_KEY:'',EMBEDDING_API_KEY:'',REDIS_URL:'',DESKTOP_NOTIFICATIONS:'false'}, windowsHide:true, stdio:['ignore','pipe','pipe'] })
    child.stdout.on('data',s=>log+=s); child.stderr.on('data',s=>log+=s); base=`http://127.0.0.1:${port}`
    await until(async()=>{ if(child.exitCode!==null) throw Error(log); try{return (await fetch(base+'/api/health')).ok}catch{return false}},'server')
  }
  function stop(){if(child&&child.exitCode===null)execFileSync('taskkill',['/PID',String(child.pid),'/T','/F'],{windowsHide:true,stdio:'ignore'});child=null}
  async function api(url,body,method='POST') {const r=await fetch(base+'/api'+url,body===undefined?{}:{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const v=await r.json();assert.ok(r.ok,`${url} ${r.status} ${JSON.stringify(v)}`);return v}
  const browser=await chromium.launch({headless:true}), errors=[]
  let page
  function setup(p){p.on('pageerror',e=>errors.push(e.message))}
  try {
    await start()
    const project=await api('/projects',{path:folder}), cid=(await api('/conversations',{title:'文件变更验收',project_id:project.id})).id
    page=await browser.newPage({viewport:{width:1440,height:900}});setup(page)
    await page.goto(base+'/chat?conv='+cid)
    const workspace=()=>page.getByRole('dialog',{name:'项目文件',exact:true}), editor=()=>page.getByRole('dialog',{name:'编辑项目文件',exact:true}), review=()=>page.getByRole('dialog',{name:'文件差异',exact:true})
    await page.locator('.project-context-button').click()
    await workspace().getByRole('button',{name:'main.py',exact:true}).click()
    await workspace().getByRole('button',{name:'编辑此文件',exact:true}).click()
    await editor().getByLabel('文件编辑内容').fill('print("after")\n# <img src=x onerror=alert(1)>\n')
    await until(async()=>(await api('/desktop-state/conversations/'+cid)).value.editor?.content.includes('after'),'editor persisted')
    // Closing/restarting with a new origin keeps the edit and baseline, not just text.
    await editor().getByRole('button',{name:'关闭并保留草稿',exact:true}).click()
    const oldBase=base; await page.close();stop();await start();assert.notEqual(base,oldBase)
    page=await browser.newPage({viewport:{width:1100,height:700}});setup(page)
    await page.goto(base+'/chat?conv='+cid);await page.locator('.project-context-button').click()
    await workspace().getByRole('button',{name:'继续编辑草稿',exact:true}).click()
    assert.ok((await editor().getByLabel('文件编辑内容').inputValue()).includes('after'))
    const other=await browser.newPage({viewport:{width:1440,height:900}});setup(other)
    await other.goto(base+'/chat?conv='+cid);await other.locator('.project-context-button').click()
    await other.getByRole('button',{name:'继续编辑草稿',exact:true}).click()
    await other.getByLabel('文件编辑内容').fill('another window edit')
    await until(async()=>(await api('/desktop-state/conversations/'+cid)).value.editor.content==='another window edit','remote editor saved')
    await editor().getByLabel('文件编辑内容').fill('print("after")\n# <img src=x onerror=alert(1)>\n# local choice\n')
    await editor().getByRole('button',{name:'保留本窗口草稿',exact:true}).click()
    await until(async()=>(await api('/desktop-state/conversations/'+cid)).value.editor.content.includes('local choice'),'editor CAS explicit choice')
    await other.close()
    await editor().getByRole('button',{name:'查看修改差异',exact:true}).click()
    await review().locator('.diff-line.add').filter({hasText:'after'}).waitFor()
    assert.equal(await fs.readFile(path.join(folder,'main.py'),'utf8'),'print("before")\n')
    assert.equal(await review().locator('img').count(),0)
    for(const [width,height,name] of [[1440,900,'desktop'],[1100,700,'small-desktop']]){
      await page.setViewportSize({width,height});await pause(100)
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
      assert.ok(await review().evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight))
      await page.screenshot({path:path.join(root,`verification/file-changes-${name}.png`),animations:'disabled'})
    }
    await review().locator('.el-dialog__headerbtn').focus();await page.keyboard.press('Shift+Tab')
    assert.ok(await review().evaluate(el=>el.contains(document.activeElement)))
    await page.keyboard.press('Escape');await review().waitFor({state:'hidden'})
    await editor().getByRole('button',{name:'查看修改差异',exact:true}).click()
    await review().getByRole('button',{name:'应用修改',exact:true}).click()
    await review().getByText('修改 · 已应用',{exact:true}).waitFor()
    assert.ok((await fs.readFile(path.join(folder,'main.py'),'utf8')).includes('after'))
    await until(async()=>(await api('/desktop-state/conversations/'+cid)).value.editor===null,'cleared draft')
    await review().getByRole('button',{name:'生成撤销差异',exact:true}).click()
    await review().getByText('修改 · 待应用',{exact:true}).waitFor()
    await review().getByRole('button',{name:'应用修改',exact:true}).click()
    await review().getByText('修改 · 已应用',{exact:true}).waitFor()
    assert.equal(await fs.readFile(path.join(folder,'main.py'),'utf8'),'print("before")\n')
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    // Optimistic file conflict preserves external changes and lets the user inspect them.
    await workspace().getByRole('button',{name:'main.py',exact:true}).click()
    await workspace().getByRole('button',{name:'编辑此文件',exact:true}).click()
    await editor().getByLabel('文件编辑内容').fill('my planned edit')
    await editor().getByRole('button',{name:'查看修改差异',exact:true}).click()
    await review().locator('.diff-line.add').filter({hasText:'my planned edit'}).waitFor()
    await fs.writeFile(path.join(folder,'main.py'),'external edit')
    await review().getByRole('button',{name:'应用修改',exact:true}).click()
    await review().getByText('修改 · 有冲突',{exact:true}).waitFor()
    await review().getByLabel('差异视图').selectOption('current')
    await review().locator('pre').filter({hasText:'external edit'}).waitFor()
    assert.equal(await fs.readFile(path.join(folder,'main.py'),'utf8'),'external edit')
    await review().getByRole('button',{name:'放弃修改',exact:true}).click()
    await review().getByText('修改 · 已放弃',{exact:true}).waitFor()
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    await editor().getByRole('button',{name:'丢弃编辑草稿',exact:true}).click()
    // Create, delete and history reopen use the same actual write workflow.
    await workspace().getByRole('button',{name:'新建文件',exact:true}).click()
    await editor().getByLabel('编辑文件路径').fill('nested/new.txt')
    await editor().getByLabel('文件编辑内容').fill('new file')
    await editor().getByRole('button',{name:'查看修改差异',exact:true}).click()
    await review().getByRole('button',{name:'应用修改',exact:true}).click()
    await review().getByText('新建 · 已应用',{exact:true}).waitFor()
    assert.equal(await fs.readFile(path.join(folder,'nested/new.txt'),'utf8'),'new file')
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    await workspace().getByRole('button',{name:'刷新文件',exact:true}).click()
    await workspace().getByRole('button',{name:'nested',exact:true}).click()
    await workspace().getByRole('button',{name:'new.txt',exact:true}).click()
    await workspace().getByRole('button',{name:'编辑此文件',exact:true}).click()
    await editor().getByRole('button',{name:'审阅删除文件',exact:true}).click()
    await review().getByRole('button',{name:'应用修改',exact:true}).click()
    await review().getByText('删除 · 已应用',{exact:true}).waitFor()
    await assert.rejects(fs.stat(path.join(folder,'nested/new.txt')))
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    await workspace().getByRole('tab',{name:'变更',exact:true}).click()
    assert.ok(await workspace().locator('.change-item').count()>=5)
    await workspace().getByRole('button',{name:'完成',exact:true}).click()
    // A failed prepare preserves the edit; lost successful apply response is reconciled.
    await page.locator('.project-context-button').click()
    await workspace().getByRole('button',{name:'新建文件',exact:true}).click()
    await editor().getByLabel('编辑文件路径').fill('response.txt')
    await editor().getByLabel('文件编辑内容').fill('lost response probe')
    await page.route('**/api/projects/*/changes',route=>route.request().method()==='POST'?route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'测试保存暂时失败'})}):route.continue())
    await editor().getByRole('button',{name:'查看修改差异',exact:true}).click()
    await editor().getByRole('alert').filter({hasText:'测试保存暂时失败'}).waitFor()
    assert.equal(await editor().getByLabel('文件编辑内容').inputValue(),'lost response probe')
    await page.unroute('**/api/projects/*/changes')
    await editor().getByRole('button',{name:'查看修改差异',exact:true}).click()
    await page.route('**/api/project-changes/*/apply',async route=>{await route.fetch();await route.abort()})
    await review().getByRole('button',{name:'应用修改',exact:true}).click()
    await review().getByText('新建 · 已应用',{exact:true}).waitFor()
    await until(async()=>(await api('/desktop-state/conversations/'+cid)).value.editor===null,'lost response reconciled')
    await page.unroute('**/api/project-changes/*/apply')
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    const longChange=await api(`/projects/${project.id}/changes`,{conversation_id:cid,request_id:crypto.randomUUID(),edit:{path:'long.txt',operation:'create',content:Array.from({length:850},(_,i)=>`Line ${i}`).join('\n')}})
    await workspace().getByRole('tab',{name:'变更',exact:true}).click()
    await workspace().locator('.change-item').filter({hasText:'long.txt'}).click()
    await review().locator('.diff-line').first().waitFor()
    assert.equal(await review().locator('.diff-line').count(),400)
    await review().getByRole('button',{name:'加载更多差异',exact:true}).click()
    await until(async()=>await review().locator('.diff-line').count()===800,'diff second page')
    await review().getByRole('button',{name:'加载更多差异',exact:true}).click()
    await review().locator('.diff-line').filter({hasText:'Line 849'}).waitFor()
    const patch=await fetch(base+`/api/project-changes/${longChange.id}/patch`);assert.ok((await patch.text()).includes('No newline at end of file'))
    await review().getByRole('button',{name:'放弃修改',exact:true}).click()
    await review().getByText('新建 · 已放弃',{exact:true}).waitFor()
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    await workspace().getByRole('button',{name:'完成',exact:true}).click()
    // Foreground approval contains a persisted review; no file until approved.
    await page.locator('textarea.textarea').fill('create foreground file')
    await page.getByRole('button',{name:'发送',exact:true}).click()
    await page.locator('.approval-card').getByRole('button',{name:'查看文件差异',exact:true}).click()
    await review().locator('.diff-line.add').filter({hasText:'agent file'}).waitFor()
    assert.equal(await review().getByRole('button',{name:'应用修改',exact:true}).count(),0)
    await assert.rejects(fs.stat(path.join(folder,'agent.py')))
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    await page.locator('.approval-card').getByRole('button',{name:'批准一次',exact:true}).click()
    await until(async()=>{try{return(await fs.readFile(path.join(folder,'agent.py'),'utf8')).includes('agent file')}catch{return false}},'agent write')
    await until(async()=>(await api('/conversations/'+cid)).messages.length===1,'foreground finalized')
    await page.reload();await page.locator('.turn-file-changes button').first().click()
    await review().getByText('新建 · 已应用',{exact:true}).waitFor()
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    const bgCid=(await api('/conversations',{title:'后台文件审批',project_id:project.id})).id
    const task=await api('/tasks/start',{question:'create background file',conversation_id:bgCid,project_id:project.id})
    await page.goto(base+'/tasks')
    await page.locator('.task-approval').getByRole('button',{name:'查看文件差异',exact:true}).click()
    await review().getByText('background.py',{exact:true}).waitFor()
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    await page.locator('.task-approval').getByRole('button',{name:'拒绝',exact:true}).click()
    await until(async()=>(await api('/tasks')).tasks.some(t=>t.id===task.id&&t.status==='done'),'background denied and done')
    await assert.rejects(fs.stat(path.join(folder,'background.py')))
    const history=await api(`/projects/${project.id}/changes`)
    assert.equal(history.changes.find(c=>c.path==='background.py').status,'rejected')
    assert.deepEqual(errors,[])
    console.log('PASS: file editing/diff/apply/undo/create/delete, conflict preservation, real agent approval/rejection, history, escaped text, keyboard focus/Escape, both desktop sizes, new-port draft restart')
  } catch(e) {if(page&&!page.isClosed())await page.screenshot({path:path.join(root,'verification/file-changes-failure.png')});throw e}
  finally {await browser.close();stop();await fs.writeFile(path.join(data,'test-server.log'),log)}
}
main().catch(e=>{console.error(e);process.exitCode=1})
