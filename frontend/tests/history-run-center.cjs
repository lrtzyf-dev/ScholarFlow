const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const net = require('node:net')
const { spawn } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '../..')
const pause = ms => new Promise(r => setTimeout(r, ms))
async function until(test, label) { const end=Date.now()+25000;while(!await test()){assert.ok(Date.now()<end,label);await pause(80)} }
async function main() {
  const out=path.join(root,'verification/history-run-center/ui'),runtime=path.join(root,'verification/runtime')
  await fs.mkdir(out,{recursive:true});await fs.mkdir(runtime,{recursive:true})
  const data=await fs.mkdtemp(path.join(runtime,'history-ui-'))
  const socket=net.createServer();await new Promise(r=>socket.listen(0,'127.0.0.1',r));const port=socket.address().port;await new Promise(r=>socket.close(r))
  const base=`http://127.0.0.1:${port}`
  const server=spawn(path.join(root,'backend/.venv/Scripts/python.exe'),['tests/history_ui_server.py',String(port)],{cwd:path.join(root,'backend'),windowsHide:true,stdio:['ignore','pipe','pipe'],env:{...process.env,DATA_DIR:data,LLM_API_KEY:'',LLM_DEMO_MODE:'1',EMBEDDING_API_KEY:'',REDIS_URL:''}})
  let log='';server.stdout.on('data',c=>log+=c);server.stderr.on('data',c=>log+=c)
  const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  const api=async(route,body,method='POST')=>{const r=await fetch(base+route,body===undefined?undefined:{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});assert.equal(r.status,200,await r.clone().text());return r.json()}
  try {
    await until(async()=>{if(server.exitCode!==null)throw Error(log);try{return (await fetch(base+'/api/health')).ok}catch{return false}},'server ready')
    const seed=await api('/__test__/seed-history',{})
    await page.goto(base+'/tasks')
    const center=page.getByRole('region',{name:'统一运行与待办'})
    await center.getByRole('list').getByText('等待调整预算',{exact:true}).waitFor()
    await center.getByRole('list').getByText('部分完成',{exact:true}).waitFor()
    await center.getByText('子任务分析',{exact:true}).waitFor()
    await page.screenshot({path:path.join(out,'run-center-desktop.png'),fullPage:true})
    await center.getByRole('button',{name:'本页标为已读'}).click()
    await until(async()=>await center.getByRole('button',{name:'本页标为已读'}).isDisabled(),'read receipts persisted')
    await page.reload();await until(async()=>await center.locator('li').count()===3,'center reload')
    assert.equal(await center.locator('.unread').count(),0)
    await center.getByRole('button',{name:'静音待办提醒'}).click()
    await center.getByRole('button',{name:'恢复待办提醒'}).waitFor();await page.reload();await center.getByRole('button',{name:'恢复待办提醒'}).waitFor()
    await page.setViewportSize({width:720,height:1000});await page.screenshot({path:path.join(out,'run-center-narrow.png'),fullPage:true})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'narrow page fits')
    await page.setViewportSize({width:1400,height:1000})
    await center.locator('[data-run-center-id="background:ui_partial"]').getByRole('button',{name:'查看并处理'}).click()
    await until(async()=>new URL(page.url()).searchParams.get('record')==='qa_ui_target','center links exact record')
    const turn=page.locator('[data-record-id="qa_ui_target"]')
    await turn.getByRole('button',{name:'编辑问题并创建修订分支'}).click()
    const dialog=page.getByRole('dialog',{name:'编辑问题与修订答案'})
    await dialog.getByLabel('修订后的问题',{exact:true}).fill('修订后的问题：只解释已有资料')
    assert.equal(await dialog.locator('input[value="answer_only"]').isChecked(),true)
    await dialog.screenshot({path:path.join(out,'revision-dialog.png')})
    await dialog.getByRole('button',{name:'创建分支草稿'}).click()
    await until(async()=>new URL(page.url()).searchParams.get('conv')!=='history-ui','new branch opened')
    const branch=new URL(page.url()).searchParams.get('conv')
    const detail=await api('/api/conversations/'+branch)
    assert.deepEqual(detail.messages.map(v=>v.question),['前一条问题'])
    assert.equal(await page.locator('.revision-banner').count(),1)
    await until(async()=>await page.locator('textarea:visible').count()>0,'draft composer')
    assert.ok(await page.locator('textarea').evaluateAll(nodes=>nodes.some(n=>n.value==='修订后的问题：只解释已有资料')))
    const sources=await api('/api/sources?conversation_id='+branch)
    assert.ok(JSON.stringify(sources).includes('fixed-version.md'))
    assert.ok(sources.items.every(item=>item.revision_id!==seed.source_id))
    await dialog.waitFor({state:'hidden'})
    await page.screenshot({path:path.join(out,'revision-branch.png'),fullPage:true})
    assert.equal((await api('/__test__/provider-calls')).length,0,'navigation/editing never calls a provider')
    assert.deepEqual(errors,[])
    await fs.writeFile(path.join(out,'report.json'),JSON.stringify({ok:true,real_provider_calls:0,synthetic_provider_calls:0,scenarios:['unified foreground/background/subtask projection','separate budget and partial states','durable read and mute preferences','720px viewport','exact result navigation','edit before target excludes future messages','independent fixed source versions','branch draft does not execute'],branch,data_directory:data,errors},null,2))
    console.log('PASS history and run center UI; 0 provider calls')
  } catch(e) {await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});await fs.writeFile(path.join(out,'failure.json'),JSON.stringify({error:String(e),errors,text:await page.locator('body').innerText(),log},null,2));throw e}
  finally {await browser.close();server.kill();await new Promise(r=>server.exitCode!==null?r():server.once('exit',r))}
}
main().catch(e=>{console.error(e);process.exitCode=1})
