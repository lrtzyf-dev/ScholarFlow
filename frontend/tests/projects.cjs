// Real project folders, SQLite and HTTP; desktop browser verification only.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const net = require('node:net')
const { spawn, execFileSync } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '../..')
const pause = ms => new Promise(r => setTimeout(r, ms))
async function until(fn, label) { const end = Date.now() + 18000; while (!await fn()) { assert.ok(Date.now() < end, label); await pause(80) } }
async function main() {
  const data = await fs.mkdtemp(path.join(root, 'verification/runtime/projects-'))
  const folder = path.join(data, '研究项目'), nested = path.join(folder, 'src')
  await fs.mkdir(nested, { recursive: true })
  await fs.writeFile(path.join(folder, 'README.md'), '项目验收资料\n<img src=x onerror=alert(1)>\n' + 'Text '.repeat(4000))
  await fs.writeFile(path.join(nested, 'notes.txt'), 'Project-specific unique context.')
  const env = { ...process.env, DATA_DIR: data, LLM_API_KEY: '', EMBEDDING_API_KEY: '', REDIS_URL: '', DESKTOP_NOTIFICATIONS: 'false', MOCK_STREAM_DELAY: '0.002' }
  let child, base, log = ''
  async function start() {
    const server = net.createServer(); await new Promise(r => server.listen(0, '127.0.0.1', r))
    const port = server.address().port; await new Promise(r => server.close(r))
    child = spawn(path.join(root, 'backend/.venv/Scripts/python.exe'), ['-m', 'uvicorn', 'app.main:app', '--host', '127.0.0.1', '--port', String(port)], { cwd: path.join(root, 'backend'), env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
    child.stdout.on('data', s => { log += s }); child.stderr.on('data', s => { log += s })
    base = `http://127.0.0.1:${port}`
    await until(async () => { if (child.exitCode !== null) throw Error(log); try { return (await fetch(base + '/api/health')).ok } catch { return false } }, 'server ready')
  }
  function stop() { if (child && child.exitCode === null) execFileSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore' }); child = null }
  async function api(url, body, method = 'POST') {
    const r = await fetch(base + '/api' + url, body === undefined ? {} : { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
    assert.ok(r.ok, `${r.status}: ${url}`); return r.json()
  }
  const browser = await chromium.launch({ headless: true }), errors = []
  try {
    await start()
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(base + '/chat')
    await page.locator('textarea.textarea').fill('保留原草稿')
    await page.locator('.project-context-button').click()
    const dialog = page.getByRole('dialog', { name: '项目文件', exact: true })
    await dialog.getByLabel('文件夹路径', { exact: true }).fill(folder)
    await dialog.getByRole('button', { name: '添加', exact: true }).click()
    await dialog.getByRole('button', { name: '关联当前会话', exact: true }).click()
    await dialog.getByText('已关联当前会话', { exact: true }).waitFor()
    await dialog.getByRole('button', { name: 'README.md', exact: true }).click()
    await dialog.locator('.file-preview pre').filter({ hasText: '项目验收资料' }).waitFor()
    assert.equal(await dialog.locator('.file-preview img').count(), 0)
    await dialog.getByRole('button', { name: '下一段', exact: true }).click()
    await dialog.locator('.file-preview footer').filter({ hasText: '8001' }).waitFor()
    await dialog.getByRole('button', { name: '引用文件', exact: true }).click()
    await dialog.getByRole('button', { name: 'src', exact: true }).click()
    await dialog.getByRole('checkbox', { name: '引用 src/notes.txt', exact: true }).check()
    await dialog.getByRole('button', { name: 'notes.txt', exact: true }).click()
    await dialog.locator('.file-preview pre').filter({ hasText: 'Project-specific' }).waitFor()
    for (const [width, height, name] of [[1440, 900, 'desktop'], [1100, 700, 'small-desktop']]) {
      await page.setViewportSize({ width, height }); await pause(100)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      assert.ok(await dialog.evaluate(el => el.getBoundingClientRect().bottom <= innerHeight))
      await page.screenshot({ path: path.join(root, `verification/projects-${name}.png`), animations: 'disabled' })
    }
    await dialog.locator('.el-dialog__headerbtn').focus()
    await page.keyboard.press('Shift+Tab')
    assert.ok(await dialog.evaluate(el => el.contains(document.activeElement)), 'dialog traps focus')
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
    assert.equal(await page.locator('textarea.textarea').inputValue(), '保留原草稿')
    const projects = await api('/projects'), project = projects[0]
    const cid = (await api(`/projects/${project.id}/conversations`)).conversations[0].id
    await until(async () => (await api(`/desktop-state/conversations/${cid}`)).value.file_paths?.length === 2, 'file references persist')
    await page.reload(); await page.locator('.project-file-chip').filter({ hasText: 'src/notes.txt' }).waitFor()
    const other = await browser.newPage({ viewport: { width: 1100, height: 700 } })
    other.on('pageerror', e => errors.push(e.message))
    await other.goto(base + '/chat?conv=' + cid)
    await other.locator('.project-context-button').filter({ hasText: '研究项目' }).waitFor()
    assert.equal(await other.locator('.project-file-chip').count(), 2)
    // Local command creates only a project AGENTS.md, preserving existing files.
    await page.locator('textarea.textarea').fill('/init')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await dialog.waitFor(); assert.ok((await fs.readFile(path.join(folder, 'AGENTS.md'), 'utf8')).includes('AGENTS.md'))
    await dialog.getByRole('button', { name: '完成', exact: true }).click()
    await page.locator('textarea.textarea').fill('检查项目文件并制定计划')
    await page.getByRole('button', { name: '计划', exact: true }).click()
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await page.getByRole('button', { name: '执行此计划', exact: true }).waitFor()
    const messages = (await api(`/conversations/${cid}`)).messages
    assert.deepEqual(messages[0].file_paths, ['README.md', 'src/notes.txt'])
    assert.ok(messages[0].trace.some(e => e.kind === 'workspace' && e.files.length === 2 && e.rules.includes('AGENTS.md')))
    assert.equal(await page.locator('.project-file-chip').count(), 0, 'sent files clear from draft')
    await fs.writeFile(path.join(nested, 'notes.txt'), 'Changed after planning')
    await page.getByRole('button', { name: '执行此计划', exact: true }).click()
    await page.getByText('原计划引用的文件已修改，请重新规划后执行', { exact: true }).waitFor()
    assert.equal((await api(`/conversations/${cid}`)).messages.length, 1)
    // @ selects a real root file; background admission receives that file.
    await page.locator('textarea.textarea').fill('@README'); await page.locator('textarea.textarea').press('End'); await page.locator('textarea.textarea').dispatchEvent('input')
    await page.locator('.mention-item').filter({ hasText: 'README.md' }).click()
    assert.equal(await page.locator('.project-file-chip').count(), 1)
    await page.locator('textarea.textarea').fill('后台检查文件')
    await page.locator('.bg-btn').click(); await page.waitForURL('**/tasks')
    await until(async () => (await api('/tasks')).tasks.some(t => t.status === 'done'), 'background plan completes')
    assert.ok((await api(`/conversations/${cid}`)).messages.some(m => m.question === '后台检查文件' && m.file_paths.includes('README.md')))
    // Draft restoration uses a fresh process, different origin and new browser context.
    await page.goto(base + '/chat?conv=' + cid)
    await page.locator('textarea.textarea').fill('重启后继续处理项目')
    await page.locator('.project-context-button').click()
    await dialog.getByRole('checkbox', { name: '引用 README.md', exact: true }).check()
    await dialog.getByRole('button', { name: '完成', exact: true }).click()
    await until(async () => { const value = (await api(`/desktop-state/conversations/${cid}`)).value; return value.text === '重启后继续处理项目' && value.file_paths.includes('README.md') }, 'save before restart')
    const oldBase = base; await page.close(); await other.close(); stop(); await start(); assert.notEqual(base, oldBase)
    const fresh = await browser.newPage({ viewport: { width: 1100, height: 700 } }); fresh.on('pageerror', e => errors.push(e.message))
    await fresh.goto(base + '/chat')
    await fresh.locator('.project-context-button').filter({ hasText: '研究项目' }).waitFor()
    await fresh.locator('.project-file-chip').filter({ hasText: 'README.md' }).waitFor()
    assert.equal(await fresh.locator('textarea.textarea').inputValue(), '重启后继续处理项目')
    await fresh.locator('.project-expand').filter({ hasText: '研究项目' }).click()
    await fresh.locator('.project-chats button').filter({ hasText: '检查项目文件并制定计划' }).waitFor()
    for (let index = 0; index < 6; index++) {
      const extra = path.join(data, `Project-${index}`)
      await fs.mkdir(extra)
      await api('/projects', { path: extra })
    }
    await fresh.getByRole('button', { name: '刷新项目列表', exact: true }).click()
    await fresh.locator('.project-expand').filter({ hasText: 'Project-5' }).waitFor()
    assert.ok(await fresh.locator('.sidebar-project-scroll').evaluate(el => el.clientHeight > 25 && el.scrollHeight > el.clientHeight), 'project list has usable independent scroll')
    const about = await fresh.getByRole('button', { name: '关于', exact: true }).boundingBox()
    assert.ok(about && about.y + about.height <= 700, 'navigation remains visible with many projects')
    await fresh.screenshot({ path: path.join(root, 'verification/projects-sidebar-small-desktop.png'), animations: 'disabled' })
    // Failure is visible and retryable; draft survives file browsing failures.
    await fresh.route('**/api/projects/*/files?**', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ detail: '读取失败测试' }) }))
    await fresh.locator('.project-context-button').click()
    const freshDialog = fresh.getByRole('dialog', { name: '项目文件', exact: true })
    await freshDialog.getByRole('alert').filter({ hasText: '读取失败测试' }).waitFor()
    await fresh.unroute('**/api/projects/*/files?**')
    await freshDialog.getByRole('button', { name: '刷新文件', exact: true }).click()
    await freshDialog.getByRole('button', { name: 'README.md', exact: true }).waitFor()
    await freshDialog.getByLabel('筛选当前目录', { exact: true }).focus()
    await fresh.keyboard.press('Escape')
    await freshDialog.waitFor({ state: 'hidden' })
    assert.equal(await fresh.locator('textarea.textarea').inputValue(), '重启后继续处理项目')
    assert.deepEqual(errors, [])
    console.log('PASS projects: browse, page, escape HTML, attach, drafts, plan/background context, stale plan rejection, sidebar, 2 desktop sizes, restart and retry')
  } finally { await browser.close(); stop() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
