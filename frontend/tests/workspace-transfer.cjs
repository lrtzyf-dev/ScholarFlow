// Desktop-only, real HTTP/SQLite/Git; no mocked filesystem or transfer API.
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path'),net=require('node:net')
const {spawn,execFileSync}=require('node:child_process')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const root=path.resolve(__dirname,'../..'),pause=ms=>new Promise(r=>setTimeout(r,ms))
async function until(fn,label){const end=Date.now()+45000;while(!await fn()){assert.ok(Date.now()<end,label);await pause(100)}}
async function main(){
  const data=await fs.mkdtemp(path.join(root,'verification/runtime/workspace-transfer-')),folder=path.join(data,'来源项目 中文')
  await fs.mkdir(folder)
  const git=(cwd,...args)=>execFileSync('git',['-C',cwd,...args],{encoding:'utf8',windowsHide:true}).trim()
  git(folder,'init','-b','main');git(folder,'config','user.name','Desktop Test');git(folder,'config','user.email','test@example.invalid');git(folder,'config','commit.gpgsign','false')
  await fs.writeFile(path.join(folder,'source.txt'),'original\n');git(folder,'add','.');git(folder,'commit','-m','Initial')
  let child,base,log='',page
  const env={...process.env,DATA_DIR:data,LLM_API_KEY:'',EMBEDDING_API_KEY:'',REDIS_URL:'',DESKTOP_NOTIFICATIONS:'false'}
  async function start(){
    const server=net.createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));const port=server.address().port;await new Promise(r=>server.close(r))
    const serverCode=`from pathlib import Path\nimport os, uvicorn\nfrom app import workspace_transfers as t\ndef fault(row, phase):\n    marker=Path(os.environ['DATA_DIR'])/'interrupt-transfer'\n    if phase=='after_write' and marker.exists():\n        marker.unlink()\n        raise RuntimeError('Desktop injected interruption')\nt._checkpoint=fault\nuvicorn.run('app.main:app',host='127.0.0.1',port=${port})`
    child=spawn(path.join(root,'backend/.venv/Scripts/python.exe'),['-c',serverCode],{cwd:path.join(root,'backend'),env,windowsHide:true,stdio:['ignore','pipe','pipe']})
    child.stdout.on('data',s=>log+=s);child.stderr.on('data',s=>log+=s);base=`http://127.0.0.1:${port}`
    await until(async()=>{if(child.exitCode!==null)throw Error(log);try{return(await fetch(base+'/api/health')).ok}catch{return false}},'server ready')
  }
  function stop(){if(child&&child.exitCode===null)execFileSync('taskkill',['/PID',String(child.pid),'/T','/F'],{windowsHide:true,stdio:'ignore'});child=null}
  async function api(url,body,method='POST'){const r=await fetch(base+'/api'+url,body===undefined?{}:{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const v=await r.json();assert.ok(r.ok,JSON.stringify(v));return v}
  const browser=await chromium.launch({headless:true}),errors=[]
  try{
    await start()
    const project=await api('/projects',{path:folder}),cid=(await api('/conversations',{title:'Git 改动迁移桌面验收',project_id:project.id})).id
    const tree=await api(`/projects/${project.id}/worktrees`,{request_id:'transfer_tree_001',name:'接收工作树 <img src=x> 😀',ref:'HEAD'})
    assert.equal(tree.status,'ready')
    const draftPath=`/desktop-state/conversations/${cid}`,state=await api(draftPath)
    await api(draftPath,{revision:state.revision,value:{...state.value,text:'迁移前文字草稿',file_paths:['source.txt']}},'PUT')
    const staged=Buffer.from([115,116,97,103,101,100,0,255]),working=Buffer.from([119,111,114,107,0,254])
    await fs.writeFile(path.join(folder,'source.txt'),staged);git(folder,'add','source.txt')
    await fs.writeFile(path.join(folder,'source.txt'),working)
    await fs.writeFile(path.join(folder,'未跟踪.bin'),Buffer.from([0,128,255,1]))
    const index=git(folder,'ls-files','--stage')
    page=await browser.newPage({viewport:{width:1440,height:900}});page.on('pageerror',e=>errors.push(e.message))
    const workspace=()=>page.getByRole('dialog',{name:'项目文件',exact:true}),panel=()=>page.getByLabel('项目工作树',{exact:true})
    const review=()=>page.getByRole('dialog',{name:'迁移 Git 改动并继续会话',exact:true})
    const stateReview=()=>page.getByRole('dialog',{name:'迁移 Git 状态并继续会话',exact:true})
    async function open(){await page.locator('.project-context-button').click();await workspace().getByRole('tab',{name:'工作树',exact:true}).click()}
    await page.goto(base+'/chat?conv='+cid)
    await until(async()=>await page.locator('textarea.textarea').inputValue()==='迁移前文字草稿','load draft')
    await open()
    await panel().getByRole('button',{name:'携带分支与提交迁移',exact:true}).click();await stateReview().waitFor()
    assert.match(await stateReview().textContent(),/来源分支会交给目标/)
    await stateReview().getByRole('button',{name:'取消迁移',exact:true}).click();await stateReview().getByText('迁移已取消。',{exact:true}).waitFor()
    await stateReview().getByRole('button',{name:'关闭',exact:true}).click()
    await fs.writeFile(path.join(tree.path,'source.txt'),'target later edit')
    await until(async()=>await panel().getByRole('button',{name:'携带 Git 改动迁移',exact:true}).isVisible().catch(()=>false),'return transfer button stable')
    await panel().getByRole('button',{name:'携带 Git 改动迁移',exact:true}).click();await review().waitFor()
    assert.ok((await review().getByRole('alert').textContent()).includes('目标已有 Git 改动'))
    assert.ok(await review().getByRole('button',{name:'备份并确认迁移',exact:true}).isDisabled())
    await page.screenshot({path:path.join(root,'verification/workspace-transfer-conflict-desktop.png'),animations:'disabled'})
    await review().getByRole('button',{name:'取消迁移',exact:true}).click();await review().getByText('迁移已取消。',{exact:true}).waitFor()
    await review().getByRole('button',{name:'关闭',exact:true}).click()
    git(tree.path,'restore','--','source.txt')
    await panel().getByRole('button',{name:'携带 Git 改动迁移',exact:true}).click();await review().waitFor()
    assert.equal(await review().locator('img').count(),0)
    assert.ok((await review().getByLabel('待迁移文件').textContent()).includes('已暂存 · 未暂存'))
    for(const[width,height,size]of[[1440,900,'desktop'],[1100,700,'small-desktop']]){
      await page.setViewportSize({width,height});await pause(180)
      const box=await review().locator('.el-dialog').boundingBox()
      assert.ok(box.x>=0&&box.y>=0&&box.x+box.width<=width&&box.y+box.height<=height,JSON.stringify(box))
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
      const button=review().getByRole('button',{name:'备份并确认迁移',exact:true})
      assert.ok(await button.evaluate(el=>{const b=el.getBoundingClientRect();return el.contains(document.elementFromPoint(b.x+b.width/2,b.y+b.height/2))}))
      await page.screenshot({path:path.join(root,`verification/workspace-transfer-review-${size}.png`),animations:'disabled'})
    }
    await page.bringToFront();await review().getByRole('button',{name:'备份并确认迁移',exact:true}).focus()
    for(let i=0;i<8;i++){await page.keyboard.press(i%2?'Shift+Tab':'Tab');assert.ok(await review().evaluate(el=>el.contains(document.activeElement)))}
    await page.keyboard.press('Escape');await review().waitFor({state:'hidden'})
    await panel().getByRole('button',{name:/^查看迁移：/}).click();await review().waitFor()
    let lost=false
    await page.route('**/workspace-transfers/*/apply',async route=>{if(!lost){lost=true;await route.fetch({timeout:45000});await route.abort('failed')}else await route.continue()})
    await review().getByRole('button',{name:'备份并确认迁移',exact:true}).click()
    await review().getByRole('alert').waitFor({timeout:45000})
    assert.equal((await api(`/conversations/${cid}/project`)).project.id,tree.project_id)
    await review().getByRole('button',{name:'备份并确认迁移',exact:true}).click()
    await review().getByText('迁移完成，当前会话已切换到目标目录。',{exact:true}).waitFor()
    const backup=await review().getByRole('link',{name:'下载迁移前后文件与索引备份'}).getAttribute('href')
    const download=await fetch(base+backup);assert.ok(download.ok);assert.equal(Buffer.from(await download.arrayBuffer()).readUInt32LE(),0x04034b50)
    assert.equal(git(folder,'status','--porcelain'),'')
    assert.deepEqual(await fs.readFile(path.join(tree.path,'source.txt')),working)
    assert.equal(git(tree.path,'ls-files','--stage'),index)
    const saved=await api(draftPath);assert.deepEqual(saved.value.file_paths,[]);assert.equal(saved.value.text,'迁移前文字草稿')
    await page.close();stop();await start()
    page=await browser.newPage({viewport:{width:1100,height:700}});page.on('pageerror',e=>errors.push(e.message))
    await page.goto(base+'/chat?conv='+cid);await page.locator('.project-context-button').waitFor();await open()
    await panel().getByRole('button',{name:'携带改动返回来源',exact:true}).click();await review().waitFor()
    await review().getByRole('button',{name:'备份并确认迁移',exact:true}).click()
    await until(async()=>(await api(`/conversations/${cid}/project`)).workspace_revision===2,'return transfer applied')
    assert.equal((await api(`/conversations/${cid}/project`)).workspace_revision,2)
    assert.equal(git(tree.path,'status','--porcelain'),'')
    assert.deepEqual(await fs.readFile(path.join(folder,'source.txt')),working)
    await page.screenshot({path:path.join(root,'verification/workspace-transfer-return-small-desktop.png'),animations:'disabled'})
    if (await review().count()) await review().getByRole('button',{name:'关闭',exact:true}).click()
    else if (await workspace().count()) await workspace().getByRole('button',{name:'完成',exact:true}).click()
    await page.reload(); await page.locator('.project-context-button').waitFor(); await open()
    await panel().getByRole('button',{name:'携带 Git 改动迁移',exact:true}).click();await review().waitFor()
    await fs.writeFile(path.join(data,'interrupt-transfer'),'once')
    await review().getByRole('button',{name:'备份并确认迁移',exact:true}).click()
    await review().getByRole('button',{name:'审阅撤回',exact:true}).waitFor({timeout:45000})
    await page.close();stop();await start()
    page=await browser.newPage({viewport:{width:1100,height:700}});page.on('pageerror',e=>errors.push(e.message))
    await page.goto(base+'/chat?conv='+cid);await page.locator('.project-context-button').waitFor();await open()
    await panel().getByRole('button',{name:/^查看迁移：.*需要核对/}).click();await review().waitFor()
    await review().getByRole('button',{name:'审阅撤回',exact:true}).click()
    await review().getByRole('alert').waitFor({state:'visible'})
    await page.screenshot({path:path.join(root,'verification/workspace-transfer-recovery-small-desktop.png'),animations:'disabled'})
    await review().getByRole('button',{name:'确认撤回迁移',exact:true}).click()
    await review().getByText('迁移已撤回，双方已恢复迁移前的文件和暂存区，会话保留在来源。',{exact:true}).waitFor({timeout:45000})
    assert.equal((await api(`/conversations/${cid}/project`)).project.id,project.id)
    assert.equal(git(tree.path,'status','--porcelain'),'')
    assert.deepEqual(await fs.readFile(path.join(folder,'source.txt')),working)
    assert.deepEqual(errors,[])
    console.log('PASS: real binary/staged/unstaged/untracked move and return; target conflict review; 1440x900/1100x700 geometry; Tab/Shift+Tab/Escape; escaped names; lost-response idempotency; downloadable backup; preserved draft; new process/port recovery; interrupted-workspace UI admission and reviewed rollback after restart')
  }catch(e){if(page&&!page.isClosed())await page.screenshot({path:path.join(root,'verification/workspace-transfer-failure.png'),fullPage:true}).catch(()=>{});console.error(log.slice(-5000));throw e}
  finally{await browser.close();stop();await fs.writeFile(path.join(data,'server.log'),log)}
}
main().catch(e=>{console.error(e);process.exitCode=1})
