// Desktop Git inspection with actual repositories and isolated HTTP/SQLite.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const net = require('node:net')
const { spawn, execFileSync } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '../..')
const pause = ms => new Promise(r => setTimeout(r, ms))
async function until(fn, name) { const end = Date.now()+20000; while (!await fn()) { assert.ok(Date.now()<end, name); await pause(80) } }
function git(cwd, ...args) { return execFileSync('git', args, { cwd, windowsHide:true, encoding:'utf8' }).trim() }
async function main() {
  const data = await fs.mkdtemp(path.join(root, 'verification/runtime/project-git-'))
  const folder = path.join(data, 'repo'), worktree = path.join(data, 'linked'), ordinary = path.join(data, 'plain')
  await fs.mkdir(folder); await fs.mkdir(ordinary)
  git(folder, 'init', '-b', 'main')
  await fs.writeFile(path.join(folder, 'main.py'), 'print("original")\n')
  await fs.writeFile(path.join(folder, 'old name.txt'), 'old name\n')
  git(folder, 'add', '--', 'main.py', 'old name.txt')
  git(folder, '-c', 'user.name=Verification', '-c', 'user.email=verification@example.invalid', 'commit', '-m', 'Initial project files')
  git(folder, 'worktree', 'add', '-b', 'feature', worktree)
  await fs.writeFile(path.join(folder, 'main.py'), 'print("staged")\n')
  git(folder, 'add', '--', 'main.py')
  await fs.writeFile(path.join(folder, 'main.py'), 'print("working")\n')
  git(folder, 'mv', '--', 'old name.txt', 'renamed name.txt')
  await fs.writeFile(path.join(folder, 'new file.txt'), '<img src=x onerror=alert(1)>\n')
  const env = {...process.env, DATA_DIR:data, LLM_API_KEY:'', EMBEDDING_API_KEY:'', REDIS_URL:'', DESKTOP_NOTIFICATIONS:'false'}
  let child, base, log = ''
  async function start() {
    const socket=net.createServer();await new Promise(r=>socket.listen(0,'127.0.0.1',r))
    const port=socket.address().port;await new Promise(r=>socket.close(r))
    child=spawn(path.join(root,'backend/.venv/Scripts/python.exe'),['-m','uvicorn','app.main:app','--host','127.0.0.1','--port',String(port)],{cwd:path.join(root,'backend'),env,windowsHide:true,stdio:['ignore','pipe','pipe']})
    child.stdout.on('data',s=>log+=s);child.stderr.on('data',s=>log+=s);base=`http://127.0.0.1:${port}`
    await until(async()=>{if(child.exitCode!==null)throw Error(log);try{return(await fetch(base+'/api/health')).ok}catch{return false}},'server')
  }
  function stop(){if(child&&child.exitCode===null)execFileSync('taskkill',['/PID',String(child.pid),'/T','/F'],{windowsHide:true,stdio:'ignore'});child=null}
  async function api(url,body,method='POST') {const response=await fetch(base+'/api'+url,body===undefined?{}:{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const result=await response.json();assert.ok(response.ok,`${url} ${response.status} ${JSON.stringify(result)}`);return result}
  const browser=await chromium.launch({headless:true}), errors=[]
  let page
  try {
    await start()
    const project=await api('/projects',{path:folder}), linked=await api('/projects',{path:worktree}), plain=await api('/projects',{path:ordinary})
    const cid=(await api('/conversations',{title:'Git verification',project_id:project.id})).id
    page=await browser.newPage({viewport:{width:1440,height:900}});page.on('pageerror',e=>errors.push(e.message))
    await page.goto(base+'/chat?conv='+cid)
    await page.locator('.project-context-button').click()
    const dialog=page.getByRole('dialog',{name:'项目文件',exact:true}), review=page.getByRole('dialog',{name:'Git 差异',exact:true})
    await dialog.getByRole('tab',{name:'版本控制',exact:true}).click()
    await dialog.locator('.git-identity').filter({hasText:'main'}).waitFor()
    assert.ok(await dialog.locator('.git-row').count()===3)
    await dialog.locator('.git-row').filter({hasText:'main.py'}).getByRole('button',{name:'已暂存',exact:true}).click()
    await review.locator('.patch-line.add').filter({hasText:'staged'}).waitFor()
    assert.equal(await review.locator('.patch-line').filter({hasText:'working'}).count(),0)
    for(const [width,height,label] of [[1440,900,'desktop'],[1100,700,'small-desktop']]){
      await page.setViewportSize({width,height});await pause(100)
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
      assert.ok(await review.evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight))
      await page.screenshot({path:path.join(root,`verification/project-git-${label}.png`),animations:'disabled'})
    }
    await review.locator('.el-dialog__headerbtn').focus();await page.keyboard.press('Shift+Tab')
    assert.ok(await review.evaluate(el=>el.contains(document.activeElement)))
    await page.keyboard.press('Escape');await review.waitFor({state:'hidden'})
    await dialog.locator('.git-row').filter({hasText:'main.py'}).getByRole('button',{name:'未暂存',exact:true}).click()
    await review.locator('.patch-line.add').filter({hasText:'working'}).waitFor()
    await review.getByRole('button',{name:'关闭',exact:true}).click()
    await dialog.locator('.git-row').filter({hasText:'new file.txt'}).getByRole('button',{name:'未跟踪',exact:true}).click()
    await review.locator('pre').filter({hasText:'<img src=x onerror=alert(1)>'}).waitFor()
    assert.equal(await review.locator('img').count(),0)
    await review.getByRole('button',{name:'关闭',exact:true}).click()
    await dialog.locator('.git-row').filter({hasText:'renamed name.txt'}).getByRole('button',{name:'已暂存',exact:true}).click()
    await review.locator('.patch-line.add').filter({hasText:'old name'}).waitFor()
    await review.getByRole('button',{name:'关闭',exact:true}).click()
    await dialog.getByRole('tab',{name:'提交记录',exact:true}).click()
    await dialog.locator('.commit-row').filter({hasText:'Initial project files'}).waitFor()
    // Fresh port and browser origin still read Git's current on-disk state.
    await page.close();stop();const oldBase=base;await start();assert.notEqual(base,oldBase)
    page=await browser.newPage({viewport:{width:1100,height:700}});page.on('pageerror',e=>errors.push(e.message))
    await page.goto(base+'/chat?conv='+cid);await page.locator('.project-context-button').click()
    const fresh=page.getByRole('dialog',{name:'项目文件',exact:true})
    await fresh.getByRole('tab',{name:'版本控制',exact:true}).click()
    await fresh.locator('.git-identity').filter({hasText:'main'}).waitFor()
    await fresh.locator('.project-item').filter({hasText:'linked'}).click()
    await fresh.getByRole('tab',{name:'版本控制',exact:true}).click()
    await fresh.locator('.git-identity').filter({hasText:'feature'}).waitFor()
    await fresh.getByText('工作树',{exact:true}).waitFor()
    await fresh.locator('.project-item').filter({hasText:'plain'}).click()
    await fresh.getByRole('tab',{name:'版本控制',exact:true}).click()
    await fresh.getByText('当前项目文件夹不是独立的 Git 仓库根目录',{exact:true}).waitFor()
    // Failed refresh preserves an actionable retry, and stale pages never mix revisions.
    await fresh.locator('.project-item').filter({hasText:'repo'}).click()
    await fresh.getByRole('tab',{name:'版本控制',exact:true}).click()
    await fresh.locator('.git-identity').filter({hasText:'main'}).waitFor()
    await page.route('**/api/projects/*/git/status*', route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'测试 Git 暂时不可用'})}))
    await fresh.getByRole('button',{name:'刷新 Git 状态',exact:true}).click()
    await fresh.getByRole('alert').filter({hasText:'测试 Git 暂时不可用'}).waitFor()
    await page.unroute('**/api/projects/*/git/status*')
    await fresh.getByRole('button',{name:'刷新 Git 状态',exact:true}).click()
    await fresh.locator('.git-row').filter({hasText:'main.py'}).waitFor()
    await fs.writeFile(path.join(folder,'main.py'),Array.from({length:850},(_,i)=>`Line ${i}`).join('\n'))
    const freshReview=page.getByRole('dialog',{name:'Git 差异',exact:true})
    await fresh.locator('.git-row').filter({hasText:'main.py'}).getByRole('button',{name:'未暂存',exact:true}).click()
    await freshReview.locator('.patch-line.add').filter({hasText:'Line 0'}).waitFor()
    await freshReview.getByRole('button',{name:'加载更多差异',exact:true}).click()
    await freshReview.locator('.patch-line.add').filter({hasText:'Line 700'}).waitFor()
    await fs.writeFile(path.join(folder,'main.py'),'updated during paging\n')
    await freshReview.getByRole('button',{name:'加载更多差异',exact:true}).click()
    await freshReview.getByRole('alert').filter({hasText:'Git 内容已变化'}).waitFor()
    await freshReview.getByRole('button',{name:'刷新 Git 差异',exact:true}).click()
    await freshReview.locator('.patch-line.add').filter({hasText:'updated during paging'}).waitFor()
    await freshReview.getByRole('button',{name:'关闭',exact:true}).click()
    for(let index=0;index<205;index++)await fs.writeFile(path.join(folder,`page-${index}.txt`),'page')
    await fresh.getByRole('button',{name:'刷新 Git 状态',exact:true}).click()
    await until(async()=>await fresh.locator('.git-row').count()===200,'first Git page')
    await fs.writeFile(path.join(folder,'new-between-pages.txt'),'new')
    await fresh.getByRole('button',{name:'加载更多',exact:true}).click()
    await fresh.getByRole('alert').filter({hasText:'Git 内容已变化'}).waitFor()
    await fresh.getByRole('button',{name:'刷新 Git 状态',exact:true}).click()
    await fresh.getByRole('button',{name:'加载更多',exact:true}).click()
    await until(async()=>await fresh.locator('.git-row').count()===209,'second Git page')
    // Project root cannot inspect its parent repo.
    const code=await api(`/projects/${project.id}/git/status`)
    assert.equal(code.branch,'main')
    const invalid=await fetch(base+`/api/projects/${project.id}/git/diff?path=..%2Fsecret&version=staged`)
    assert.equal(invalid.status,400)
    assert.deepEqual(errors,[])
    console.log('PASS project-git: real staged/unstaged/renamed/untracked diffs, escaped text, history, linked worktree, non-Git empty state, two desktop sizes, focus/Escape, new-port restart')
  } catch(e){if(page&&!page.isClosed())await page.screenshot({path:path.join(root,'verification/project-git-failure.png')});throw e}
  finally{await browser.close();stop();await fs.writeFile(path.join(data,'test-server.log'),log)}
}
main().catch(e=>{console.error(e);process.exitCode=1})
