// Real UI and isolated backend; the Python fixture replaces every provider transport.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const net = require('node:net')
const { spawn } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(__dirname, '../..')
const pause = ms => new Promise(r => setTimeout(r, ms))
async function until(test, label) { const end = Date.now() + 25000; while (!await test()) { assert.ok(Date.now() < end, label); await pause(80) } }
async function main() {
  const output = path.join(root, 'verification/provider-adapters/ui')
  await fs.mkdir(output, {recursive:true})
  const runtime = path.join(root, 'verification/runtime')
  await fs.mkdir(runtime, {recursive:true})
  const data = await fs.mkdtemp(path.join(runtime, 'provider-adapters-'))
  const socket = net.createServer()
  await new Promise(r => socket.listen(0, '127.0.0.1', r))
  const port = socket.address().port
  await new Promise(r => socket.close(r))
  const base = `http://127.0.0.1:${port}`
  const server = spawn(path.join(root, 'backend/.venv/Scripts/python.exe'), ['tests/provider_adapter_ui_server.py', String(port)], {
    cwd:path.join(root,'backend'), windowsHide:true, stdio:['ignore','pipe','pipe'],
    env:{...process.env, DATA_DIR:data, LLM_API_KEY:'', LLM_DEMO_MODE:'0', EMBEDDING_API_KEY:'', REDIS_URL:'', DESKTOP_NOTIFICATIONS:'false'},
  })
  let log = ''
  server.stdout.on('data', c => { log += c }); server.stderr.on('data', c => { log += c })
  const browser = await chromium.launch({headless:true})
  const page = await browser.newPage({viewport:{width:1440,height:1000}})
  const pageErrors = []; page.on('pageerror', e => pageErrors.push(e.message))
  const api = async (route, body, method='POST') => { const r = await fetch(base+route, body === undefined ? undefined : {method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}); assert.equal(r.status,200,await r.clone().text()); return r.json() }
  const providerCalls = () => api('/__test__/provider-calls')
  try {
    await until(async () => { if(server.exitCode !== null) throw Error(log); try { return (await fetch(base+'/api/health')).ok } catch { return false } }, 'isolated backend startup')
    const catalog = await api('/api/model-profiles')
    const profile = catalog.profiles.find(v => v.id === catalog.default_profile_id)
    await api(`/api/model-profiles/${profile.id}`, {expected_version:profile.version, api_key:'synthetic-ui-model-key'}, 'PUT')
    await page.goto(base+'/settings')
    const row = page.locator(`[data-profile-id="${profile.id}"]`)
    await row.getByRole('button',{name:'能力诊断',exact:true}).click()
    const panel = row.getByRole('region',{name:'模型分项诊断'})
    await until(async () => await panel.locator('.capability-row').count() === 9,'capabilities preview')
    assert.equal((await providerCalls()).length,0)
    for (const label of ['文本回答','流式输出','三轮工具往返','图片理解','推理字段','JSON 对象输出','聊天用量','原生搜索与链接阅读','原生文件理解']) {
      const button = panel.getByRole('button',{name:`测试${label}`,exact:true})
      await button.click()
      await until(async () => !(await button.isDisabled()),`probe ${label} completes`)
      assert.equal(await button.locator('..').locator('.capability-state').innerText(),'已验证')
    }
    assert.equal((await providerCalls()).length,15)
    await api('/__test__/delay-next-chat')
    await panel.getByRole('button',{name:'测试三轮工具往返',exact:true}).click()
    await until(async () => (await providerCalls()).length === 16,'tool test dispatched')
    await panel.getByRole('button',{name:'取消本项测试',exact:true}).click()
    await until(async () => (await panel.locator('.capability-result').innerText()).includes('取消'),'cancel tool test')
    assert.equal((await providerCalls()).length,16,'cancel stops later tool rounds')
    await api('/__test__/delay-next-chat')
    await panel.getByRole('button',{name:'测试原生文件理解',exact:true}).click()
    await until(async () => (await providerCalls()).length === 18,'file read after upload dispatched')
    await panel.getByRole('button',{name:'取消本项测试',exact:true}).click()
    await until(async () => await panel.getByRole('button',{name:'清理测试文件',exact:true}).count() === 1,'known file retained for cleanup')
    await panel.getByRole('button',{name:'清理测试文件',exact:true}).click()
    await until(async () => await panel.getByRole('button',{name:'清理测试文件',exact:true}).count() === 0,'explicit cleanup confirmed')
    assert.equal((await providerCalls()).length,19)
    await page.screenshot({path:path.join(output,'capabilities-desktop.png'),fullPage:true})
    await page.reload(); await row.getByRole('button',{name:'能力诊断',exact:true}).click()
    await until(async () => await row.locator('.capability-state.supported').count() === 9,'capabilities persist')
    assert.equal((await providerCalls()).length,19)
    await page.setViewportSize({width:720,height:1000})
    await page.screenshot({path:path.join(output,'capabilities-narrow.png'),fullPage:true})
    await page.setViewportSize({width:1440,height:1000})
    await api('/api/service-tools/deepseek',{expected_version:0, enabled_services:['research','files'],api_key:'synthetic-ui-service-key'},'PUT')
    await page.goto(base+'/chat')
    await page.locator('[data-testid="conversation-sources"] input[type=file]').setInputFiles({name:'cloud-ui.md',mimeType:'text/markdown',buffer:Buffer.from('# Synthetic UI file\nValue: 17.\n')})
    await page.getByRole('button',{name:/管理资料/}).click()
    const dialog = page.getByRole('dialog',{name:'会话资料',exact:true})
    await dialog.locator('.cloud-files > summary').click()
    await until(async () => await dialog.getByLabel('固定原件',{exact:true}).locator('option').count() > 1,'source in cloud selector')
    const option = await dialog.getByLabel('固定原件',{exact:true}).locator('option').nth(1).getAttribute('value')
    await dialog.getByLabel('固定原件',{exact:true}).selectOption(option)
    await dialog.getByRole('button',{name:'查看上传内容',exact:true}).click()
    await dialog.getByRole('button',{name:'确认发送原件到 DeepSeek',exact:true}).waitFor()
    assert.equal((await providerCalls()).length,19,'review does not upload')
    await dialog.getByRole('button',{name:'确认发送原件到 DeepSeek',exact:true}).click()
    await until(async () => (await dialog.locator('.cloud-files').innerText()).includes('在当前会话附加对应的原件'),'upload available')
    assert.ok((await dialog.locator('.cloud-files').innerText()).includes('服务端可能已转换或解析'))
    assert.ok((await dialog.locator('.cloud-files').innerText()).includes('不能核对远端原件哈希'))
    assert.equal((await providerCalls()).length,20)
    await dialog.screenshot({path:path.join(output,'cloud-file-available.png')})
    await dialog.getByRole('button',{name:'删除此远端文件',exact:true}).click()
    await until(async () => (await dialog.locator('.cloud-files').innerText()).includes('远端已删除或未上传'),'delete confirmed')
    assert.equal((await providerCalls()).length,21)
    assert.deepEqual(pageErrors,[])
    await fs.writeFile(path.join(output,'report.json'),JSON.stringify({ok:true,real_provider_calls:0,synthetic_provider_calls:21,
      scenarios:['nine explicit capability probes','three-round tool roundtrip','two native tools actually execute','random token requires uploaded file','cancel further tool rounds','cancel file read retains remote cleanup','explicit cleanup action','reload without requests','720px settings','MD immutable source cloud preview','explicit upload with TTL','processed-size disclosure without remote-byte identity claim','confirmed remote delete'],
      calls:await providerCalls(),pageErrors,data_directory:data},null,2))
    console.log('PASS provider adapters UI; 0 real calls, 21 synthetic calls')
  } catch(e) {
    await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{})
    await fs.writeFile(path.join(output,'failure.json'),JSON.stringify({error:String(e),pageErrors,text:await page.locator('body').innerText().catch(()=>''),log},null,2))
    throw e
  } finally { await browser.close(); server.kill(); await new Promise(r => server.exitCode !== null ? r() : server.once('exit',r)) }
}
main().catch(e=>{console.error(e);process.exitCode=1})
