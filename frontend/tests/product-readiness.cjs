const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path'),net=require('node:net')
const {spawn}=require('node:child_process'),{chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const root=path.resolve(__dirname,'../..'),pause=ms=>new Promise(r=>setTimeout(r,ms))
async function until(test,label){const end=Date.now()+25000;while(!await test()){assert.ok(Date.now()<end,label);await pause(80)}}
async function main(){
  const out=path.join(root,'verification/product-readiness/ui'),runtime=path.join(root,'verification/runtime')
  await fs.mkdir(out,{recursive:true});await fs.mkdir(runtime,{recursive:true})
  const data=await fs.mkdtemp(path.join(runtime,'product-ui-')),socket=net.createServer()
  await new Promise(r=>socket.listen(0,'127.0.0.1',r));const port=socket.address().port;await new Promise(r=>socket.close(r))
  const base=`http://127.0.0.1:${port}`,server=spawn(path.join(root,'backend/.venv/Scripts/python.exe'),['tests/product_readiness_ui_server.py',String(port)],{cwd:path.join(root,'backend'),windowsHide:true,stdio:['ignore','pipe','pipe'],env:{...process.env,DATA_DIR:data,LLM_API_KEY:'',LLM_BASE_URL:'https://api.deepseek.com/v1',LLM_MODEL:'deepseek-flash',LLM_DEMO_MODE:'0',EMBEDDING_API_KEY:'',REDIS_URL:''}})
  let log='';server.stdout.on('data',c=>log+=c);server.stderr.on('data',c=>log+=c)
  const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  const api=async(route,body)=>{const r=await fetch(base+route,body===undefined?undefined:{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});assert.equal(r.status,200,await r.clone().text());return r.json()}
  try{
    await until(async()=>{if(server.exitCode!==null)throw Error(log);try{return(await fetch(base+'/api/health')).ok}catch{return false}},'server ready')
    await page.goto(base+'/chat')
    const guide=page.getByRole('region',{name:'首次研究引导'}),composer=page.locator('.composer-input')
    await guide.getByText(/当前模型 deepseek-flash 待配置/).waitFor()
    const textarea=page.locator('textarea:visible').first()
    await textarea.fill('保留我的未发送草稿')
    await guide.getByRole('button',{name:'配置或检查模型'}).click()
    const editor=page.getByRole('dialog',{name:'编辑模型'})
    await editor.waitFor();await editor.getByRole('button',{name:'取消',exact:true}).click()
    assert.equal(await textarea.inputValue(),'保留我的未发送草稿')
    await guide.getByRole('button',{name:'准备资料问答'}).click()
    assert.equal(await textarea.inputValue(),'保留我的未发送草稿')
    await textarea.dispatchEvent('keydown',{key:'Enter',code:'Enter',isComposing:true,bubbles:true})
    assert.equal(await textarea.inputValue(),'保留我的未发送草稿')
    const before=await api('/__test__/counts')
    await guide.getByRole('button',{name:'体验隔离示例'}).click()
    const demo=page.getByRole('dialog',{name:'本地交互示例 · 非模型回答'})
    await demo.getByRole('button',{name:'示例问题：两组有什么差别？'}).click()
    await demo.getByRole('button',{name:'[示例引用 1]',exact:true}).click()
    await demo.getByText('示例原句 · 第 1 段',{exact:true}).waitFor()
    await demo.screenshot({path:path.join(out,'isolated-demo.png')})
    await page.keyboard.press('Escape');await demo.waitFor({state:'hidden'})
    assert.deepEqual(await api('/__test__/counts'),before)
    await guide.getByRole('button',{name:'检查本地环境'}).click()
    const diagnostics=page.getByRole('dialog',{name:'配置诊断',exact:true})
    await diagnostics.getByText('诊断历史与安全恢复',{exact:true}).click()
    await diagnostics.getByRole('button',{name:'保存一次本地检查'}).click()
    await diagnostics.getByRole('button',{name:'审阅脱敏导出内容'}).first().waitFor()
    await diagnostics.getByRole('button',{name:'审阅脱敏导出内容'}).first().click()
    const preview=page.getByRole('dialog',{name:'审阅脱敏诊断导出'})
    await preview.waitFor();assert.ok(!(await preview.innerText()).includes(data))
    await page.keyboard.press('Escape');await preview.waitFor({state:'hidden'});assert.ok(await diagnostics.isVisible())
    await api('/__test__/seed-probe',{})
    await diagnostics.getByRole('button',{name:'刷新诊断历史'}).click()
    await diagnostics.getByRole('button',{name:'先核对调用回执与费用'}).click()
    const receiptDialog=page.getByRole('dialog',{name:'核对调用回执与费用',exact:true})
    await receiptDialog.getByText('失败 · 合成测试',{exact:true}).waitFor()
    assert.ok((await receiptDialog.innerText()).includes('尚无记录'))
    assert.ok((await receiptDialog.innerText()).includes('合成测试，不计入真实费用'))
    await page.keyboard.press('Escape');await receiptDialog.waitFor({state:'hidden'});assert.ok(await diagnostics.isVisible())
    await page.keyboard.press('Escape');await diagnostics.waitFor({state:'hidden'})
    assert.equal(await guide.getByRole('button',{name:'检查本地环境'}).evaluate(n=>n===document.activeElement),true,'focus returns to diagnostics trigger')
    await guide.getByRole('button',{name:'稍后再看'}).click();await guide.waitFor({state:'hidden'})
    await page.reload();await until(async()=>await page.locator('textarea:visible').count()>0,'reload composer')
    assert.equal(await guide.count(),0)
    await page.goto(base+'/settings');await page.getByRole('button',{name:'重新打开使用引导'}).click();await guide.waitFor()
    await page.setViewportSize({width:720,height:1000})
    await page.locator('.chat-page').evaluate(e=>e.scrollTop=0)
    await page.locator('.chat-scroll').evaluate(e=>e.scrollTop=0)
    await guide.locator('h2').scrollIntoViewIfNeeded()
    await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))))
    const geometry=await page.evaluate(()=>Object.fromEntries(['.top-bar','.chat-page','.chat-scroll-wrap','.chat-scroll','.journey','.journey h2'].map(s=>{const n=document.querySelector(s),r=n.getBoundingClientRect(),c=getComputedStyle(n);return[s,{top:r.top,bottom:r.bottom,height:r.height,scrollTop:n.scrollTop,overflow:c.overflow,justify:c.justifyContent,flex:c.flex}]})))
    await fs.writeFile(path.join(out,'narrow-geometry.json'),JSON.stringify(geometry,null,2))
    assert.ok(geometry['.journey h2'].top>=geometry['.top-bar'].bottom,'guide heading can be fully brought into view')
    await page.screenshot({path:path.join(out,'first-use-narrow.png'),fullPage:true})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'720px document fits')
    const seeded=await api('/__test__/seed-citation',{})
    assert.equal((await api('/api/onboarding')).milestones.find(v=>v.id==='citation').complete,false)
    await page.goto(`${base}/sources/${seeded.revision_id}?conversation=${seeded.conversation_id}&locator=${seeded.locator_id}`)
    await page.locator('[data-source-line="2"]').waitFor()
    await until(async()=>(await api('/api/onboarding')).milestones.find(v=>v.id==='citation').complete,'rendered source visit is observed')
    await page.screenshot({path:path.join(out,'first-fixed-citation.png'),fullPage:true})
    assert.equal((await api('/__test__/provider-calls')).length,0)
    assert.deepEqual(errors,[])
    await fs.writeFile(path.join(out,'report.json'),JSON.stringify({ok:true,real_provider_calls:0,synthetic_provider_calls:0,scenarios:['fresh empty model waits for configuration','cancel preserves unsent draft','guide compose preserves existing draft','IME composition does not submit','isolated demo writes no research records','local diagnostics saved and redacted preview','synthetic failed receipt is separate from actual provider billing and never auto-retried','nested dialog Escape and focus return','skip persists across reload','settings reopens guide','720px heading geometry and viewport','citation observed only after fixed source location renders'],limits:['This developer-driven browser exercise is not independent user validation or Windows native-host validation.'],data_directory:data,errors},null,2))
    console.log('PASS product journey and diagnostics UI; zero provider calls')
  }catch(e){await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});await fs.writeFile(path.join(out,'failure.json'),JSON.stringify({error:String(e),errors,text:await page.locator('body').innerText(),log},null,2));throw e}
  finally{await browser.close();server.kill();await new Promise(r=>server.exitCode!==null?r():server.once('exit',r))}
}
main().catch(e=>{console.error(e);process.exitCode=1})
