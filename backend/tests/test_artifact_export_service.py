@pytest.mark.parametrize("format", ["docx", "xlsx", "svg", "bundle"])
def test_real_container_checks_reject_even_if_payload_checksum_is_replaced(db, format):
    from app import artifact_exports
    from app.artifact_models import ArtifactExport
    from sqlalchemy import update
    item = analysis(db) if format != "docx" else document(db)
    receipt = create(db, item, format)
    row = db.get(ArtifactExport, receipt["export_id"])
    if format == "svg":
        payload = row.payload.replace(b"</svg>", b"<script>bad()</script></svg>")
    elif format == "xlsx":
        from openpyxl import load_workbook
        workbook = load_workbook(io.BytesIO(row.payload))
        workbook["RawData"]["A2"] = "=2+2"
        output = io.BytesIO(); workbook.save(output); workbook.close()
        payload = output.getvalue()
    else:
        with zipfile.ZipFile(io.BytesIO(row.payload)) as archive:
            members = {name: archive.read(name) for name in archive.namelist()}
        if format == "docx":
            members["word/document.xml"] = members["word/document.xml"].replace("正文".encode(), "造假".encode())
        else:
            members["data.csv"] = members["data.csv"].replace(b"1.500", b"9.500")
            manifest = json.loads(members["manifest.json"])
            manifest["files"]["data.csv"] = store.digest(members["data.csv"])
            members["manifest.json"] = json.dumps(manifest).encode()
        output = io.BytesIO()
        with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
            for name, content in members.items():
                archive.writestr(name, content)
        payload = output.getvalue()
    # Deliberately replace the simple checksum and its non-secret metadata
    # checksum too: independent actual-format checks must still reject.
    row.payload, row.payload_sha256, row.payload_size = payload, store.digest(payload), len(payload)
    validation = {key: value for key, value in row.validation.items() if key != "binding_sha256"}
    if format == "svg":
        validation = deepcopy(validation)
        validation["descriptor"]["svg_sha256"] = store.digest(payload)
    patched = {**validation, "binding_sha256": artifact_exports._binding(row, validation)}
    db.execute(update(ArtifactExport).where(ArtifactExport.id == row.id).values(payload=payload,
        payload_sha256=row.payload_sha256, payload_size=row.payload_size, validation=patched))
    db.commit()
    with pytest.raises(HTTPException) as error:
        artifact_exports.get(db, item["id"], receipt["export_id"])
    assert error.value.status_code == 409


