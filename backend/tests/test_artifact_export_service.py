def test_concurrent_same_request_returns_one_saved_payload(db, monkeypatch):
    from concurrent.futures import ThreadPoolExecutor
    from threading import Barrier
    from app import artifact_exports, artifact_export_formats as formats
    from app.artifact_models import ArtifactExport
    from app.db import SessionLocal
    item = document(db)
    barrier = Barrier(2)
    original = formats.render
    def together(*a, **kw):
        result = original(*a, **kw)
        barrier.wait(timeout=15)
        return result
    monkeypatch.setattr(formats, "render", together)
    def export():
        with SessionLocal() as other:
            return create(other, item)
    with ThreadPoolExecutor(max_workers=2) as pool:
        left, right = list(pool.map(lambda _: export(), range(2)))
    assert left["export_id"] == right["export_id"]
    assert left["payload_sha256"] == right["payload_sha256"]
    assert db.query(ArtifactExport).count() == 1


