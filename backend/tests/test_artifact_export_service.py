def document(db, **overrides):
    return store.create(db, **({"request_id": "export-source-123", "title": "固定成果",
        "kind": "document", "content": "# 方法\n正文\n\n| 组别 | 分数 |\n| --- | --- |\n| A | 1 |\n",
        "evidence": [], "analysis": {}} | overrides))


def analysis(db, **overrides):
    return document(db, **({"kind": "analysis", "content": "label,value\n=1+1,1.500\n@sample,\n+second,2.5\n",
        "analysis": {"category_column": "label", "numeric_columns": ["value"],
                     "chart_type": "line", "units": {"value": "kg"}}} | overrides))


def create(db, item, format="docx", **overrides):
    from app import artifact_exports
    return artifact_exports.create(db, **({"artifact_id": item["id"],
        "conversation_id": item.get("conversation_id"), "revision_id": item["current_revision_id"],
        "request_id": "export-request-123", "format": format} | overrides))


def test_actual_xlsx_bytes_are_persisted_and_reopenable(db):
    from app import artifact_exports
    from app.artifact_models import ArtifactExport
    from openpyxl import load_workbook
    item = analysis(db)
    receipt = create(db, item, "xlsx")
    row = artifact_exports.get(db, item["id"], receipt["export_id"], None)
    assert db.query(ArtifactExport).count() == 1
    assert row.payload_sha256 == store.digest(row.payload)
    workbook = load_workbook(io.BytesIO(row.payload), data_only=False)
    assert workbook["RawData"]["A2"].value == "=1+1"
    assert workbook["RawData"]["A2"].data_type == "s"
    assert workbook["RawData"]["B2"].value == "1.500"
    assert workbook["NumericData"]["B3"].value is None
    assert workbook["Statistics"]["E2"].value == 2
    assert receipt["validation"]["native_open"] == "not_assessed"
    assert "payload" not in receipt


